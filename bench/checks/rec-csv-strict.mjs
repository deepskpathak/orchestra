import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const m = await import(pathToFileURL(`${process.cwd()}/src/csv.js`).href);
const p = m.parseCsv;
assert.deepEqual(p('a,b\n1,2\n3,4\n'), [{ a: '1', b: '2' }, { a: '3', b: '4' }]);
assert.deepEqual(p('a,b\r\n"x, y","say ""hi"""\r\n'), [{ a: 'x, y', b: 'say "hi"' }]);
assert.deepEqual(p('a,b\n"l1\nl2",z'), [{ a: 'l1\nl2', b: 'z' }]);
assert.deepEqual(p('﻿a,b\n1,2\n'), [{ a: '1', b: '2' }], 'the BOM is stripped from the first header');
assert.deepEqual(p('a;b\n"1;2";3\n', { delimiter: ';' }), [{ a: '1;2', b: '3' }]);
assert.deepEqual(p('a,b\n\n1,2\n\n'), [{ a: '1', b: '2' }], 'empty lines are skipped');
assert.deepEqual(p('a,b\n"",\n'), [{ a: '', b: '' }]);
assert.deepEqual(p('a\n"\n\n"\n'), [{ a: '\n\n' }], 'empty lines inside quotes are data');
assert.deepEqual(p(''), []);
assert.deepEqual(p('﻿'), []);
assert.deepEqual(p('a,b\n'), []);
const line = (text, n, opts) => assert.throws(() => p(text, opts), (e) => e instanceof Error && new RegExp(`line ${n}\\b`).test(e.message), `${JSON.stringify(text)} must throw naming line ${n}`);
line('a,b\n1,2\n"open,3\n', 3);
line('a,b\n1,2,3\n', 2);
line('a,b\n"x\ny",1\n4\n', 4, undefined);
line('a,b\n1,a"b\n', 2);
line('a,b\n"x"y,1\n', 2);
line('a,b\n\n\n1\n', 4);
line('a;b\n1,2\n', 2, { delimiter: ';' });
assert.throws(() => p('a,a\n1,2\n'), Error);
